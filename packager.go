// addFileToZip adds a single file to the zip archive under nameInZip.
func addFileToZip(zw *zip.Writer, srcPath, nameInZip string) error {
	src, err := os.Open(srcPath)
	if err != nil {
		return err
	}
	defer src.Close()

	info, err := src.Stat()
	if err != nil {
		return err
	}

	header, err := zip.FileInfoHeader(info)
	if err != nil {
		return err
	}
	header.Name = nameInZip
	header.Method = zip.Deflate

	w, err := zw.CreateHeader(header)
	if err != nil {
		return err
	}
	_, err = io.Copy(w, src)
	return err
}

// addDirToZip recursively adds srcDir into the zip under prefix/.
// Symlinks are resolved to their targets (required for JRE bin/).
func addDirToZip(zw *zip.Writer, srcDir, prefix string) error {
	return filepath.WalkDir(srcDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		rel, err := filepath.Rel(srcDir, path)
		if err != nil {
			return err
		}
		nameInZip := prefix + "/" + filepath.ToSlash(rel)

		if d.IsDir() {
			if !strings.HasSuffix(nameInZip, "/") {
				nameInZip += "/"
			}
			_, err = zw.Create(nameInZip)
			return err
		}

		// Resolve symlinks so the zip contains real files
		realPath, err := filepath.EvalSymlinks(path)
		if err != nil {
			realPath = path
		}

		info, err := os.Stat(realPath)
		if err != nil {
			return err
		}

		header, err := zip.FileInfoHeader(info)
		if err != nil {
			return err
		}
		header.Name = nameInZip
		header.Method = zip.Deflate
		header.SetMode(info.Mode())

		w, err := zw.CreateHeader(header)
		if err != nil {
			return err
		}

		f, err := os.Open(realPath)
		if err != nil {
			return err
		}
		defer f.Close()
		_, err = io.Copy(w, f)
		return err
	})
}

// buildPayloadZip creates an in-memory zip containing:
//
//	app.jar  (or app.war)
//	jre/     (minimal JRE)
//
// Returns the raw zip bytes and a hex SHA-256 of those bytes.
func buildPayloadZip(jarPath, jreDir string) ([]byte, string, error) {
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)

	jarName := filepath.Base(jarPath)
	logInfo("Embedding %s", jarName)
	if err := addFileToZip(zw, jarPath, jarName); err != nil {
		return nil, "", fmt.Errorf("embed JAR: %w", err)
	}

	logInfo("Embedding JRE")
	if err := addDirToZip(zw, jreDir, "jre"); err != nil {
		return nil, "", fmt.Errorf("embed JRE: %w", err)
	}

	if err := zw.Close(); err != nil {
		return nil, "", err
	}

	data := buf.Bytes()
	sum := fmt.Sprintf("%x", sha256.Sum256(data))
	return data, sum, nil
}

