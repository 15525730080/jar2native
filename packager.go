// JavaPackager orchestrates the full packaging workflow.
type JavaPackager struct {
	cfg *Config
	jdk *JDKManager
}

// NewJavaPackager creates a new JavaPackager from the given config.
func NewJavaPackager(cfg *Config) (*JavaPackager, error) {
	jdk, err := NewJDKManager(cfg.JDKPath)
	if err != nil {
		return nil, err
	}
	return &JavaPackager{cfg: cfg, jdk: jdk}, nil
}

// Package runs the full packaging workflow.
func (p *JavaPackager) Package() error {
	start := time.Now()

	jarPath, err := filepath.Abs(p.cfg.JarFile)
	if err != nil {
		return fmt.Errorf("invalid jar path: %w", err)
	}

	// ── Validate ────────────────────────────────────────────────────────────
	if err := p.validate(jarPath); err != nil {
		return err
	}

	// ── Prepare temp workspace ──────────────────────────────────────────────
	tmpDir, err := os.MkdirTemp("", "jar2native-*")
	if err != nil {
		return fmt.Errorf("failed to create temp dir: %w", err)
	}
	defer os.RemoveAll(tmpDir)

	jreDir := filepath.Join(tmpDir, "jre")

	if p.jdk.IsLegacy() {
		// ── Java 8 and below: copy the existing JRE, skip jdeps/jlink ───────
		logInfo("Java %d detected — using full JRE copy (jlink not available)", p.jdk.Version)
		if err := NewJREBuilder(p.jdk).Build(jreDir, ""); err != nil {
			return err
		}
	} else {
		// ── Java 9+: analyze modules then build minimal JRE with jlink ───────
		logStep("Analyzing module dependencies")
		analyzer := NewModuleAnalyzer(p.jdk)
		analyzed, err := analyzer.Analyze(jarPath, p.cfg.AllModules)
		if err != nil {
			return fmt.Errorf("module analysis failed: %w", err)
		}
		finalModules := MergeModules(analyzed, p.cfg.ExtraModules)
		logInfo("Final modules: %s", finalModules)

		if err := NewJREBuilder(p.jdk).Build(jreDir, finalModules); err != nil {
			return err
		}
	}

	// ── Build payload zip (JAR + JRE in memory) ─────────────────────────────
	logStep("Building payload (JAR + JRE)")
	payloadData, payloadHash, err := buildPayloadZip(jarPath, jreDir)
	if err != nil {
		return fmt.Errorf("build payload: %w", err)
	}
	logInfo("Payload size: %.1f MB  hash: %s…", float64(len(payloadData))/1e6, payloadHash[:12])

	// ── Compile final binary ────────────────────────────────────────────────
	appName := strings.TrimSuffix(filepath.Base(jarPath), filepath.Ext(jarPath))
	builder := NewBinaryBuilder("dist")

	outFile, err := builder.Build(
		jarPath,
		payloadData,
		payloadHash,
		appName,
		p.cfg.TargetOS,
		p.cfg.TargetArch,
	)
	if err != nil {
		return err
	}

	elapsed := time.Since(start)
	fmt.Printf("\n✅ Done in %.2fs\n", elapsed.Seconds())
	fmt.Printf("   Output : %s\n", outFile)
	fmt.Printf("   Size   : %.1f MB\n", float64(fileSize(outFile))/1e6)
	fmt.Println()
	fmt.Println("The binary is fully self-contained — just run it:")
	if p.cfg.TargetOS == "windows" {
		fmt.Printf("  %s.exe\n", appName)
	} else {
		fmt.Printf("  chmod +x dist/%s && dist/%s\n", appName, appName)
	}
	return nil
}

func fileSize(path string) int64 {
	info, err := os.Stat(path)
	if err != nil {
		return 0
	}
	return info.Size()
}

// validate checks that the input file exists and is a valid JAR/WAR.
func (p *JavaPackager) validate(jarPath string) error {
	if _, err := os.Stat(jarPath); os.IsNotExist(err) {
		return fmt.Errorf("input file not found: %s", jarPath)
	}

	ext := strings.ToLower(filepath.Ext(jarPath))
	if ext != ".jar" && ext != ".war" {
		return fmt.Errorf("only JAR and WAR files are supported")
	}

	if ext == ".jar" {
		if ok, err := hasMainClass(p.jdk, jarPath); err != nil || !ok {
			return fmt.Errorf("JAR file missing Main-Class attribute in MANIFEST.MF")
		}
	}
	return nil
}

// hasMainClass checks whether the JAR's MANIFEST.MF contains a Main-Class entry.
// It reads the zip directly — no external jar command needed.
func hasMainClass(_ *JDKManager, jarPath string) (bool, error) {
	r, err := zip.OpenReader(jarPath)
	if err != nil {
		return false, fmt.Errorf("open JAR: %w", err)
	}
	defer r.Close()

	for _, f := range r.File {
		if f.Name != "META-INF/MANIFEST.MF" {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return false, err
		}
		data, err := io.ReadAll(rc)
		rc.Close()
		if err != nil {
			return false, err
		}
		return strings.Contains(string(data), "Main-Class"), nil
	}
	return false, nil
}
