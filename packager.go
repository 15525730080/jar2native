// runnerTemplate is the Go source code that gets compiled into the final binary.
// It embeds the payload zip and extracts it on first run.
const runnerTemplate = `// Code generated by jar2native. DO NOT EDIT.
package main

import (
	_ "embed"
	"archive/zip"
	"bytes"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
)

//go:embed payload.zip
var payloadZip []byte

const payloadHash = "{{.Hash}}"
const jarName     = "{{.JarName}}"

func main() {
	dir, err := extractOnce()
	if err != nil {
		fmt.Fprintf(os.Stderr, "[ERROR] Failed to extract payload: %v\n", err)
		os.Exit(1)
	}

	javaExe := "java"
	if runtime.GOOS == "windows" {
		javaExe = "java.exe"
	}
	javaBin := filepath.Join(dir, "jre", "bin", javaExe)
	jarFile := filepath.Join(dir, jarName)

	cmd := exec.Command(javaBin, "-jar", jarFile)
	cmd.Args = append(cmd.Args, os.Args[1:]...)
	cmd.Stdin  = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	if err := cmd.Run(); err != nil {
		if exitErr, ok := err.(*exec.ExitError); ok {
			os.Exit(exitErr.ExitCode())
		}
		fmt.Fprintf(os.Stderr, "[ERROR] %v\n", err)
		os.Exit(1)
	}
}

// extractOnce extracts the payload zip to a stable cache directory.
// If the directory already exists (same hash), extraction is skipped.
func extractOnce() (string, error) {
	cacheDir, err := os.UserCacheDir()
	if err != nil {
		cacheDir = os.TempDir()
	}
	dir := filepath.Join(cacheDir, "jar2native", payloadHash)

	// Already extracted?
	if _, err := os.Stat(filepath.Join(dir, ".extracted")); err == nil {
		return dir, nil
	}

	fmt.Fprintln(os.Stderr, "[jar2native] First run: extracting runtime...")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return "", err
	}

	r, err := zip.NewReader(bytes.NewReader(payloadZip), int64(len(payloadZip)))
	if err != nil {
		return "", err
	}

	for _, f := range r.File {
		target := filepath.Join(dir, filepath.FromSlash(f.Name))

		if f.FileInfo().IsDir() {
			os.MkdirAll(target, 0755)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(target), 0755); err != nil {
			return "", err
		}

		rc, err := f.Open()
		if err != nil {
			return "", err
		}
		out, err := os.OpenFile(target, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, f.Mode())
		if err != nil {
			rc.Close()
			return "", err
		}
		_, copyErr := io.Copy(out, rc)
		out.Close()
		rc.Close()
		if copyErr != nil {
			return "", copyErr
		}
	}

	// Mark as fully extracted
	marker, err := os.Create(filepath.Join(dir, ".extracted"))
	if err != nil {
		return "", err
	}
	marker.Close()

	return dir, nil
}
`

// ─────────────────────────────────────────────────────────────────────────────
// BinaryBuilder: generates a temp Go project and compiles it
// ─────────────────────────────────────────────────────────────────────────────

type runnerData struct {
	Hash    string
	JarName string
}

// BinaryBuilder compiles the final self-contained binary.
type BinaryBuilder struct {
	outputDir string
}

func NewBinaryBuilder(outputDir string) *BinaryBuilder {
	return &BinaryBuilder{outputDir: outputDir}
}

// Build generates a Go project in a temp dir, embeds the payload, and compiles.
// targetOS/targetArch are GOOS/GOARCH values (empty = current platform).
func (b *BinaryBuilder) Build(
	jarPath string,
	payloadData []byte,
	payloadHash string,
	outputName string,
	targetOS string,
	targetArch string,
) (string, error) {
	// ── Temp project directory ──────────────────────────────────────────────
	tmpDir, err := os.MkdirTemp("", "jar2native-runner-*")
	if err != nil {
		return "", fmt.Errorf("create temp dir: %w", err)
	}
	defer os.RemoveAll(tmpDir)

	// ── Write payload.zip ───────────────────────────────────────────────────
	payloadPath := filepath.Join(tmpDir, "payload.zip")
	if err := os.WriteFile(payloadPath, payloadData, 0644); err != nil {
		return "", fmt.Errorf("write payload.zip: %w", err)
	}

	// ── Write main.go from template ─────────────────────────────────────────
	tmpl, err := template.New("runner").Parse(runnerTemplate)
	if err != nil {
		return "", fmt.Errorf("parse runner template: %w", err)
	}
	var mainBuf bytes.Buffer
	if err := tmpl.Execute(&mainBuf, runnerData{
		Hash:    payloadHash,
		JarName: filepath.Base(jarPath),
	}); err != nil {
		return "", fmt.Errorf("render runner template: %w", err)
	}
	if err := os.WriteFile(filepath.Join(tmpDir, "main.go"), mainBuf.Bytes(), 0644); err != nil {
		return "", fmt.Errorf("write main.go: %w", err)
	}

	// ── Write go.mod ────────────────────────────────────────────────────────
	goMod := "module runner\n\ngo 1.21\n"
	if err := os.WriteFile(filepath.Join(tmpDir, "go.mod"), []byte(goMod), 0644); err != nil {
		return "", fmt.Errorf("write go.mod: %w", err)
	}

	// ── Determine output path (must be absolute; go build runs in tmpDir) ──
	absOutputDir, err := filepath.Abs(b.outputDir)
	if err != nil {
		return "", fmt.Errorf("resolve output dir: %w", err)
	}
	if err := os.MkdirAll(absOutputDir, 0755); err != nil {
		return "", fmt.Errorf("create output dir: %w", err)
	}
	outFile := filepath.Join(absOutputDir, outputName)
	if targetOS == "windows" {
		outFile += ".exe"
	}

	// ── Run go build ────────────────────────────────────────────────────────
	logStep("Compiling binary: %s", outFile)
	goBin, err := findGo()
	if err != nil {
		return "", err
	}

	cmd := exec.Command(goBin, "build", "-ldflags", "-s -w", "-o", outFile, ".")
	cmd.Dir = tmpDir
	cmd.Env = append(os.Environ(),
		"CGO_ENABLED=0",
	)
	if targetOS != "" {
		cmd.Env = append(cmd.Env, "GOOS="+targetOS)
	}
	if targetArch != "" {
		cmd.Env = append(cmd.Env, "GOARCH="+targetArch)
	}

	if out, err := cmd.CombinedOutput(); err != nil {
		return "", fmt.Errorf("go build failed: %w\n%s", err, string(out))
	}

	logOK("Binary compiled: %s", outFile)
	return outFile, nil
}

// findGo locates the go binary.
func findGo() (string, error) {
	// Try PATH first
	if p, err := exec.LookPath("go"); err == nil {
		return p, nil
	}
	// Common install locations
	candidates := []string{
		"/opt/homebrew/bin/go",
		"/usr/local/go/bin/go",
		"/usr/bin/go",
	}
	for _, c := range candidates {
		if _, err := os.Stat(c); err == nil {
			return c, nil
		}
	}
	return "", fmt.Errorf("go binary not found; please install Go from https://go.dev/dl/")
}

